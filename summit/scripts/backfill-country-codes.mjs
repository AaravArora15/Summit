#!/usr/bin/env node
/**
 * Backfills locations.country_code (see migrations/0026_wildcard_same_country.sql)
 * by reverse-geocoding every location's own stored point through Nominatim,
 * the same service scripts/seed-csv.mjs used to forward-geocode them.
 *
 * Reverse geocoding the actual stored coordinate, rather than trusting the
 * CSV's own free-text Country column, is deliberate: a few CSV rows name a
 * multi-country range ("France/Italy/Switzerland") and Nominatim's own
 * forward-geocode for a route name can land just across a border from the
 * country the name implies. What matters for the same-country Wildcard rule
 * is which country the point actually landed in, not the label in the CSV.
 *
 * Reads slug + lon/lat straight out of supabase/seed/0001_world_locations.sql
 * and supabase/seed/0005_macritchie_signage.sql (no DB connection needed),
 * writes supabase/seed/0006_location_country_codes.sql.
 *
 *   node scripts/backfill-country-codes.mjs
 *
 * Results are cached to scripts/.country-code-cache.json, same convention as
 * .geocode-cache.json, so a re-run after adding a handful of new locations
 * only geocodes the new ones.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SEED_DIR = path.join(__dirname, '..', '..', 'supabase', 'seed');
const CACHE_PATH = path.join(__dirname, '.country-code-cache.json');
const OUT_PATH = path.join(SEED_DIR, '0006_location_country_codes.sql');
const NOMINATIM = 'https://nominatim.openstreetmap.org/reverse';

/** Nominatim's published limit is 1 request/second. */
const DELAY_MS = 1100;

const ROW_RE = /'([a-z0-9]+)',\s*'(?:[^']|'')*',\s*st_point\((-?[0-9.]+),\s*(-?[0-9.]+)\)::geography/g;

async function loadPlaces() {
  const files = ['0001_world_locations.sql', '0005_macritchie_signage.sql'];
  const places = [];
  for (const file of files) {
    const text = await readFile(path.join(SEED_DIR, file), 'utf8');
    for (const m of text.matchAll(ROW_RE)) {
      places.push({ slug: m[1], lng: Number(m[2]), lat: Number(m[3]) });
    }
  }
  return places;
}

async function loadCache() {
  try {
    return JSON.parse(await readFile(CACHE_PATH, 'utf8'));
  } catch {
    return {};
  }
}

async function saveCache(cache) {
  await writeFile(CACHE_PATH, JSON.stringify(cache, null, 1));
}

async function reverseGeocode(lat, lng) {
  const url = `${NOMINATIM}?lat=${lat}&lon=${lng}&format=jsonv2&zoom=3`;
  const res = await fetch(url, { headers: { 'User-Agent': 'summit-app/1.0 (wildcard country backfill)' } });
  if (!res.ok) throw new Error(`Nominatim ${res.status}`);
  const body = await res.json();
  return body?.address?.country_code ? body.address.country_code.toUpperCase() : null;
}

async function main() {
  const places = await loadPlaces();
  const cache = await loadCache();
  const results = [];
  let calls = 0;

  for (const place of places) {
    const cacheKey = `${place.lat.toFixed(5)},${place.lng.toFixed(5)}`;
    let code = cache[cacheKey];

    if (code === undefined) {
      calls++;
      try {
        code = await reverseGeocode(place.lat, place.lng);
        // Only cache a real answer, including a genuine "no country here"
        // (open ocean, say). A network/HTTP failure is not that: caching it
        // as null would make it permanent and unretryable on the next run.
        cache[cacheKey] = code;
      } catch (err) {
        console.error(`  ${place.slug}: ${err.message}`);
        code = null;
      }
      await new Promise((r) => setTimeout(r, DELAY_MS));
    }

    if (code) results.push({ slug: place.slug, code });
    else console.error(`  ${place.slug}: no country resolved`);
  }

  await saveCache(cache);

  const lines = [
    '-- Backfills locations.country_code (0026_wildcard_same_country.sql) by',
    "-- reverse-geocoding each location's own stored point through Nominatim.",
    '-- Generated by scripts/backfill-country-codes.mjs. Regenerate rather than hand-edit.',
    '',
    'begin;',
    'set local search_path = public, extensions;',
    '',
    'update locations set country_code = v.code',
    'from (values',
    results.map((r) => `  (${sq(r.slug)}, ${sq(r.code)})`).join(',\n') + '',
    ') as v(slug, code)',
    'where locations.slug = v.slug;',
    '',
    'commit;',
    '',
  ];

  await writeFile(OUT_PATH, lines.join('\n'));
  console.log(`\n${results.length}/${places.length} resolved (${calls} live lookups). Wrote ${path.relative(process.cwd(), OUT_PATH)}`);
}

function sq(s) {
  return `'${String(s).replace(/'/g, "''")}'`;
}

main();
